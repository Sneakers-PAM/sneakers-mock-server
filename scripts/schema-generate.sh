#!/usr/bin/env bash
# Regenerates packages/gateway-client/src/generated from the committed schema copy and the
# operations in src/operations.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root/packages/gateway-client"
npx graphql-codegen --config codegen.ts
# Only the typed documents are used; the preset's string-lookup helper is dropped.
find src/generated -maxdepth 1 \( -name gql.ts -o -name index.ts \) -delete
# The human schema itself, for the mock to answer in the gateway's exact shapes.
node -e '
const fs = require("node:fs");
fs.writeFileSync(
  "src/generated/schemaSdl.ts",
  "/** The gateway schema (schema/schema.graphqls), generated by scripts/schema-generate.sh. */\nexport const SCHEMA_SDL = " +
    JSON.stringify(fs.readFileSync("schema/schema.graphqls", "utf8")) +
    ";\n",
);
'
npx prettier --write --log-level warn src/generated
